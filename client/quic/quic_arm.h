#pragma once /* защита от повторного включения заголовка */

/* ================================================================
 * «Взвод» записи: общий момент старта для трассы и ввода.
 *
 * RDP_CAPTURE_ARM=signal — трасса не пишется, ввод не пишется и не
 * воспроизводится, пока процессу xfreerdp не придёт сигнал SIGUSR1.
 * Момент прихода сигнала — ноль времени для трассы и для ввода.
 * Скрипт записи шлёт сигнал, когда сессия полностью загрузилась
 * (рабочий стол и приложения сценария на месте), — так в трассу не
 * попадает подключение и запуск, а запись и повтор начинаются из
 * одинакового состояния экрана.
 *
 * Без RDP_CAPTURE_ARM — прежнее поведение: запись сразу, трасса
 * отсчитывает время от открытия файла, ввод — от активации сессии.
 *
 * SIGUSR1 выбран потому, что FreeRDP его не перехватывает
 * (libfreerdp/utils/signal_posix.c обрабатывает TERM/INT и аварийные).
 * ================================================================ */

#include <stdint.h> /* uint64_t */

/* Включить режим ожидания сигнала, если задан RDP_CAPTURE_ARM=signal.
 * Можно звать несколько раз (трасса и ввод зовут оба) — сработает один. */
void quic_arm_init(void);

/* 1 — включён режим ожидания сигнала */
int quic_arm_signal_mode(void);

/* 1 — сигнал пришёл (в обычном режиме всегда 1) */
int quic_arm_is_armed(void);

/* Момент прихода сигнала по монотонным часам, нс (0, если не пришёл) */
uint64_t quic_arm_t0_ns(void);

/* Текущее время по монотонным часам, нс */
uint64_t quic_arm_now_ns(void);
