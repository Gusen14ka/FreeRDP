/* ================================================================
 * Запись и воспроизведение ввода пользователя в xfreerdp.
 * Подробно — в TRACE.md, раздел «Запись и воспроизведение ввода».
 *
 * Переменные окружения:
 *   RDP_INPUT_RECORD=/путь/input.csv  — записать каждое событие ввода,
 *                                       которое клиент отправил серверу
 *   RDP_INPUT_SCRIPT=/путь/input.csv  — воспроизвести события из файла
 *                                       в те же моменты от активации сессии
 * Можно обе сразу: тогда в RECORD попадёт то, что реально отправил
 * проигрыватель (удобно для проверки). Без переменных ничего не делает.
 *
 * Формат файла — в quic_input_script.h.
 * ================================================================ */

#include <freerdp/freerdp.h> /* freerdp, BOOL */

/* Вызывать в PreConnect ПОСЛЕ quic_trace_pre_connect: открывает файлы и
 * ставит обёртку WritePdu, через которую подхватываются функции ввода. */
BOOL quic_input_pre_connect(freerdp* instance);

/* Вызывать в PostDisconnect: останавливает воспроизведение, закрывает файлы. */
void quic_input_close(void);
